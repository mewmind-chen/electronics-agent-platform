#!/usr/bin/env node
/**
 * Write machine-local absolute plugin paths into generated overlays.
 * Official dsh --patch requires an absolute `name` for a local TypeScript/JS plugin.
 * Do not commit a home-directory path as the only config.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const helloPlugin = join(root, "packages/dsh-hello/src/index.js");
const importPlugin = join(root, "packages/dsh-import/src/index.js");
const partPlugin = join(root, "packages/dsh-part/src/index.js");
const companyPlugin = join(root, "packages/dsh-company/src/index.js");

const helloOverlay = `# Generated by scripts/write-overlays.mjs — do not edit by hand.
# Official form: docs/user/develop/basic/index.md
- insert:
    - id: electronics-hello
      name: '${helloPlugin}'
    - id: electronics-import
      name: '${importPlugin}'
    - id: electronics-part
      name: '${partPlugin}'
    - id: electronics-company
      name: '${companyPlugin}'
`;

mkdirSync(join(root, "runtime"), { recursive: true });
writeFileSync(join(root, "runtime/hello.cordis.yml"), helloOverlay);
writeFileSync(
  join(root, "packages/dsh-hello/cordis.patch.yml"),
  `# Generated companion for packages/dsh-hello (absolute plugin path).
- insert:
    - id: electronics-hello
      name: '${helloPlugin}'
`,
);
writeFileSync(
  join(root, "packages/dsh-import/cordis.patch.yml"),
  `# Generated companion for packages/dsh-import (absolute plugin path).
- insert:
    - id: electronics-import
      name: '${importPlugin}'
`,
);
process.stderr.write(`[overlays] hello=${helloPlugin}\n[overlays] import=${importPlugin}\n`);
